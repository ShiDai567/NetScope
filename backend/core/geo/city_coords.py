def city_coord(name: str) -> tuple[float, float] | None:
    """城市/省名 → (lat, lng)；未收录返回 None。"""
    if not name:
        return None
    hit = _CITY_COORDS.get(name)
    if hit:
        return hit
    hit = _PROVINCE_CENTROIDS.get(name)
    if hit:
        return hit
    # 去掉常见后缀再试一次（如 "杭州" vs "杭州市"）
    for trimmed in (name.rstrip("市"), name.rstrip("省")):
        if trimmed != name:
            hit = _CITY_COORDS.get(trimmed) or _PROVINCE_CENTROIDS.get(trimmed)
            if hit:
                return hit
    return None
